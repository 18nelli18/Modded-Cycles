function creditHtml(c) {
  const url = "https://github.com/" + c.repo;
  const link = (txt) => `<a href="${esc(url)}" target="_blank" rel="noopener">${esc(txt)}</a>`;
  return c.kind === "based"
    ? t("credit_based", { repo: link(c.repo.split("/")[1]), who: esc(c.who) })
    : t("credit_by", { who: link(c.who) });
}

